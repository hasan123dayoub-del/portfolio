// Generates cv/cv.html and the CV PDF from src/data.ts, so the CV never drifts from the website.
// PDF printing uses an installed Edge/Chrome (override with BROWSER_PATH).
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import {
  certifications,
  education,
  experience,
  languages,
  profile,
  projects,
  skills,
  volunteering,
} from '../src/data.ts'

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const bare = (url) => url.replace(/^https?:\/\//, '').replace(/\/$/, '')
const pipes = (s) => s.replaceAll(' · ', ' | ')

const lines = (arr) => `<ul>${arr.map((p) => `<li>${esc(p)}</li>`).join('')}</ul>`

const css = `
      @page { size: A4; margin: 14mm 15mm; }
      * { box-sizing: border-box; }
      body { margin: 0; font: 10.2pt/1.45 'Segoe UI', Arial, sans-serif; color: #1f2937; }
      h1 { margin: 0; font-size: 26pt; color: #0f172a; letter-spacing: -0.5px; }
      .title { margin: 4px 0 8px; font-size: 12pt; font-weight: 600; color: #0e7490; }
      .contact { font-size: 9pt; color: #475569; line-height: 1.6; }
      .contact span + span::before { content: '|'; margin: 0 8px; color: #94a3b8; }
      header { padding-bottom: 10px; border-bottom: 3px solid #0f172a; }
      h2 { margin: 16px 0 6px; padding-bottom: 3px; border-bottom: 1px solid #e2e8f0; font-size: 9pt; letter-spacing: 2px; text-transform: uppercase; color: #0f172a; }
      p { margin: 0 0 4px; }
      ul { margin: 3px 0 8px; padding-left: 16px; }
      li { margin-bottom: 2px; }
      .row { display: flex; justify-content: space-between; align-items: baseline; gap: 12px; }
      .date { font-size: 9pt; color: #64748b; white-space: nowrap; }
      .item { margin-top: 8px; break-inside: avoid; }
      .item b { color: #0f172a; }
      .tech { font-size: 8.8pt; color: #0e7490; margin: 1px 0 2px; }
      .small { font-size: 8.8pt; color: #64748b; }
      .skill b { color: #0f172a; }`

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>${esc(profile.name)} - CV</title>
    <style>${css}
    </style>
  </head>
  <body>
    <!-- Generated by scripts/build-cv.mjs from src/data.ts. Edit the data file, not this one. -->
    <header>
      <h1>${esc(profile.name)}</h1>
      <div class="title">${esc(profile.title)} | ${esc(profile.stack.replaceAll(' · ', ', '))}</div>
      <div class="contact">
        <span>${esc(profile.location)}</span><span>${esc(profile.email)}</span><span>${esc(profile.phone)}</span><br />
        <span>${esc(bare(profile.linkedin))}</span><span>${esc(bare(profile.github))}</span><span>${esc(bare(profile.site))}</span>
      </div>
    </header>

    <h2>Profile</h2>
    <p>${esc(profile.summary)}</p>

    <h2>Technical Skills</h2>
    ${skills.map((g) => `<p class="skill"><b>${esc(g.group)}:</b> ${esc(g.items.join(', '))}</p>`).join('\n    ')}

    <h2>Professional Experience</h2>
    ${experience
      .map(
        (e) => `<div class="item">
      <div class="row"><span><b>${esc(e.role)}</b> | ${esc(e.company)}</span><span class="date">${esc(e.period)}</span></div>
      ${lines(e.points)}
    </div>`,
      )
      .join('\n    ')}

    <h2>Selected Projects</h2>
    ${projects
      .map(
        (p) => `<div class="item">
      <b>${esc(p.name)} | ${esc(p.subtitle)}</b> (${esc(p.kind)})
      <div class="tech">${esc(p.tech.join(', '))} | ${esc(bare(p.repo))}</div>
      ${lines(p.points)}
    </div>`,
      )
      .join('\n    ')}

    <h2>Certifications</h2>
    ${certifications
      .map(
        (c) => `<div class="item">
      <div class="row"><span><b>${esc(c.name)}</b></span>${c.date ? `<span class="date">${esc(c.date)}</span>` : ''}</div>
      <div class="small">${esc(pipes(c.detail))}${c.credential ? ` | Credential ID ${esc(c.credential)}` : ''}</div>
    </div>`,
      )
      .join('\n    ')}

    <h2>Education</h2>
    <div class="row"><span><b>${esc(education.degree)}</b></span><span class="date">${esc(education.period)}</span></div>
    <div class="small">${esc(education.school)}</div>

    <h2>Volunteering</h2>
    <div class="row"><span><b>${esc(volunteering.role.split(' · ')[0])}</b> | ${esc(volunteering.role.split(' · ')[1] ?? '')}</span><span class="date">${esc(volunteering.period)}</span></div>
    <ul><li>${esc(volunteering.text)}</li></ul>

    <h2>Languages</h2>
    <p>${languages.map((l) => `<b>${esc(l.name)}:</b> ${esc(l.level)}`).join(' &nbsp;|&nbsp; ')}</p>
  </body>
</html>
`

const htmlPath = resolve('cv/cv.html')
const pdfPath = resolve('public/Hasan_Dayoub_CV.pdf')
mkdirSync(resolve('cv'), { recursive: true })
writeFileSync(htmlPath, html)

const candidates = [
  process.env.BROWSER_PATH,
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
  '/usr/bin/google-chrome',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
].filter(Boolean)
const browser = candidates.find((p) => existsSync(p))
if (!browser) throw new Error('No Edge/Chrome found. Set BROWSER_PATH to a browser executable.')

execFileSync(browser, ['--headless', '--disable-gpu', '--no-pdf-header-footer', `--print-to-pdf=${pdfPath}`, pathToFileURL(htmlPath).href], {
  stdio: 'ignore',
})
console.log(`CV written: ${pdfPath}`)

// Keep a personal copy in Documents, if that folder exists.
const docs = join(homedir(), 'Documents')
if (existsSync(docs)) {
  copyFileSync(pdfPath, join(docs, 'Hasan_Dayoub_CV.pdf'))
  console.log(`CV copied to: ${join(docs, 'Hasan_Dayoub_CV.pdf')}`)
}
